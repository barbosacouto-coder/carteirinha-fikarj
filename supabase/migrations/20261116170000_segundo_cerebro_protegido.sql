create or replace function public.segundo_cerebro_buscar(
  p_busca text default '',
  p_categoria text default '',
  p_limite integer default 60,
  p_offset integer default 0
)
returns table (
  id uuid,
  titulo text,
  categoria text,
  resumo text,
  data_documento date,
  tipo text,
  nome_original text,
  storage_path text,
  tamanho_bytes bigint,
  sha256 text,
  criado_em timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'acesso negado' using errcode = '42501';
  end if;
  return query
    select d.id, d.titulo, d.categoria, d.resumo, d.data_documento, d.tipo,
           d.nome_original, d.storage_path, d.tamanho_bytes, d.sha256, d.criado_em
      from public.segundo_cerebro_documentos d
     where d.ativo
       and (btrim(coalesce(p_categoria, '')) = '' or lower(d.categoria) = lower(btrim(p_categoria)))
       and (
         btrim(coalesce(p_busca, '')) = ''
         or lower(d.titulo) like '%' || lower(btrim(p_busca)) || '%'
         or lower(coalesce(d.resumo, '')) like '%' || lower(btrim(p_busca)) || '%'
         or lower(d.categoria) like '%' || lower(btrim(p_busca)) || '%'
         or lower(d.tipo) like '%' || lower(btrim(p_busca)) || '%'
       )
     order by d.data_documento desc nulls last, d.titulo
     limit least(greatest(coalesce(p_limite, 60), 1), 100)
    offset greatest(coalesce(p_offset, 0), 0);
end;
$$;

create or replace function public.segundo_cerebro_registrar_acesso(p_documento uuid)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'acesso negado' using errcode = '42501';
  end if;
  if not exists (
    select 1 from public.segundo_cerebro_documentos
     where id = p_documento and ativo
  ) then
    raise exception 'documento indisponível' using errcode = 'P0002';
  end if;
  insert into public.segundo_cerebro_acessos (documento_id, usuario_id)
  values (p_documento, auth.uid());
end;
$$;

revoke all on function public.segundo_cerebro_buscar(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.segundo_cerebro_buscar(text, text, integer, integer) to authenticated;
revoke all on function public.segundo_cerebro_registrar_acesso(uuid) from public, anon, authenticated;
grant execute on function public.segundo_cerebro_registrar_acesso(uuid) to authenticated;

