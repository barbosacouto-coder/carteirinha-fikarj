create table if not exists public.segundo_cerebro_documentos (
  id uuid primary key default gen_random_uuid(),
  titulo text not null check (char_length(btrim(titulo)) between 1 and 180),
  categoria text not null check (char_length(btrim(categoria)) between 1 and 80),
  resumo text check (resumo is null or char_length(resumo) <= 600),
  data_documento date,
  tipo text not null check (tipo in ('PDF','DOCX','XLSX','HTML','HTM','MD','TXT','JPG','JPEG','PNG')),
  nome_original text not null check (char_length(btrim(nome_original)) between 1 and 255),
  storage_path text not null unique check (storage_path !~ '(^|/)(\.\.|\.)($|/)' and storage_path !~ '[\\:]'),
  tamanho_bytes bigint not null check (tamanho_bytes between 1 and 26214400),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  ativo boolean not null default true,
  criado_por uuid not null default auth.uid() references auth.users(id),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.segundo_cerebro_acessos (
  id bigint generated by default as identity primary key,
  documento_id uuid not null references public.segundo_cerebro_documentos(id) on delete restrict,
  usuario_id uuid not null references auth.users(id),
  acessado_em timestamptz not null default now()
);

